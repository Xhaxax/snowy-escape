#!/usr/bin/env python3
"""Pack animation frames into a horizontal strip, cropped to the union bounding box.

usage: strip.py NAME FPS frame1.png frame2.png ...   (or a single sheet with --split N)
Writes assets/img/NAME.png and registers it in src/manifest.js.
"""
import json, os, re, sys
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MANIFEST = os.path.join(ROOT, 'src', 'manifest.js')


def load_manifest():
    if not os.path.exists(MANIFEST):
        return {'images': [], 'anims': {}}
    txt = open(MANIFEST).read()
    return json.loads(re.search(r'=\s*(\{.*\});', txt, re.S).group(1))


def save_manifest(m):
    with open(MANIFEST, 'w') as f:
        f.write('// Generated by tools/strip.py — sprite strips made from PixelLab art.\n')
        f.write('window.SE_MANIFEST = ' + json.dumps(m, indent=1) + ';\n')


def main():
    args = sys.argv[1:]
    split = None
    if '--split' in args:
        i = args.index('--split'); split = int(args[i + 1]); del args[i:i + 2]
    pad = 1
    if '--pad' in args:
        i = args.index('--pad'); pad = int(args[i + 1]); del args[i:i + 2]
    name, fps, files = args[0], float(args[1]), args[2:]
    frames = []
    if split:
        sheet = Image.open(files[0]).convert('RGBA')
        fw = sheet.width // split
        frames = [sheet.crop((k * fw, 0, (k + 1) * fw, sheet.height)) for k in range(split)]
    else:
        frames = [Image.open(f).convert('RGBA') for f in files]
    boxes = [f.getbbox() for f in frames if f.getbbox()]
    x0 = max(0, min(b[0] for b in boxes) - pad); y0 = max(0, min(b[1] for b in boxes) - pad)
    x1 = min(frames[0].width, max(b[2] for b in boxes) + pad); y1 = max(b[3] for b in boxes)
    w, h = x1 - x0, y1 - y0
    out = Image.new('RGBA', (w * len(frames), h))
    for k, f in enumerate(frames):
        out.paste(f.crop((x0, y0, x1, y1)), (k * w, 0))
    out.save(os.path.join(ROOT, 'assets', 'img', name + '.png'))
    m = load_manifest()
    if len(frames) > 1:
        m['anims'][name] = {'frames': len(frames), 'fps': fps}
        if name in m['images']: m['images'].remove(name)
    elif name not in m['images']:
        m['images'].append(name)
    if name not in m['images'] and len(frames) > 1:
        pass
    save_manifest(m)
    print(f'{name}: {len(frames)} frames of {w}x{h} (crop origin {x0},{y0})')


if __name__ == '__main__':
    main()
